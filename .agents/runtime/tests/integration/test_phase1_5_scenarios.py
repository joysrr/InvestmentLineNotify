class TestStateSchema:
    """v7.22 schema TypedDict 對齊 + reducer 正確性"""

    def test_initial_state_well_formed(self):
        s = create_initial_state(request="test")
        assert s["status"] == "dispatched"
        assert s["task_class"] == "feature"
        assert s["task_class_source"] == "keyword"
        assert s["autonomy_mode"] == "gate-at-design"
        assert s["created_by"] == "@Lead"
        assert s["original_request"] == "test"
        assert s["schema_version"] == "v1"

    def test_assert_checkpoint_safe_passes_initial(self):
        s = create_initial_state(request="test")
        # 不 raise
        assert_checkpoint_safe(s)

    def test_assert_checkpoint_safe_blocks_socket(self):
        import socket

        s = create_initial_state(request="test")
        s["bad_field"] = socket.socket()  # type: ignore[typeddict-unknown-key]
        with pytest.raises(TypeError, match="不可被.*序列化"):
            assert_checkpoint_safe(s)

    def test_serialize_deserialize_roundtrip(self):
        s = create_initial_state(request="rename foo to bar")
        s["task_class"] = "modify-existing"
        s["target_agent"] = "@Architect"

        yaml_text = serialize_to_routing_ticket(s)
        assert "schema_version: v1" in yaml_text
        assert "task_class: modify-existing" in yaml_text
        assert "auto-generated by LangGraph runtime v8.0" in yaml_text

        recovered = deserialize_from_routing_ticket(yaml_text)
        assert recovered["task_class"] == "modify-existing"
        assert recovered["target_agent"] == "@Architect"


